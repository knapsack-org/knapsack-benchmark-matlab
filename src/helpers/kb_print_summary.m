function kb_print_summary(s, algos, total_time, out_file)
%KB_PRINT_SUMMARY  Print the summary table, the ranking and the output file.
  fprintf('\n%-6s %9s %9s %11s %12s %12s %10s %12s\n', 'algo', 'optimal', 'mean gap', ...
          'total t(s)', 'median t(s)', 'median mem', 'x time ref', 'mean ops');
  for a = 1:numel(algos)
    p = s.algorithms.(algos{a});
    fprintf('%-6s %5d/%-3d %8.2f%% %11.3f %12.5f %12s %10.1f %12.0f\n', algos{a}, ...
            p.num_optimal, s.num_instances, p.mean_gap_percent, p.total_wall_time_s, ...
            p.median_wall_time_s, kb_human_bytes(p.median_working_memory_bytes), ...
            p.median_time_ratio_vs_reference, p.mean_operations);
  end
  fprintf('Fastest (median time): %s\nTotal %.1f s\nOutput: %s\n', ...
          strjoin(s.ranking_by_median_time, ' < '), total_time, out_file);
end
