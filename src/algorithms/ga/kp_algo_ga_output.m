function O = kp_algo_ga_output()
%KP_ALGO_GA_OUTPUT  Benchmark adapter and JSON description of 'ga'.
%   O.run(v, w, C, acfg, seed)  runs KP_ALGO_GA_MAIN, returns the common result struct
%   O.entry(acfg, env)          entry of the JSON "algorithms" array
%   O.schema.entry / .details   JSON Schema of that entry / of results.ga.details
  O = struct('run', @run_algo, 'entry', @build_entry, 'schema', describe());
end

function out = run_algo(v, w, C, acfg, seed)
  [items, info] = kp_algo_ga_main(v, w, C, acfg, seed);
  out = struct('label', label(), 'exact', false, 'proven_optimal', false, ...
               'items', items, 'working_memory_bytes', info.working_memory_bytes, ...
               'operations', info.evaluations, 'operations_unit', 'fitness evaluations');
  out.details = struct('evaluations', info.evaluations, 'generations', info.generations);
end

function e = build_entry(acfg, env) %#ok<INUSD>
  L = kp_algo_ga_loader();
  e = struct('id', L.id, 'label', label(), 'description', L.description, 'short_label', L.short_label, 'exact', L.exact, ...
             'reference', L.reference, 'config', acfg);
end

function s = label()
  L = kp_algo_ga_loader();
  s = L.label;
end

function s = describe()
  s.entry = jsondecode(['{"type": "object", "additionalProperties": false,' ...
    ' "required": ["id", "label", "description", "short_label", "exact", "reference", "config"],' ...
    ' "properties": {"id": {"enum": ["ga"]}, "label": {"type": "string"}, "description": {"type": "string"},' ...
    ' "short_label": {"type": "string"}, "exact": {"type": "boolean"},' ...
    ' "reference": {"type": "boolean"},' ...
    ' "config": {"type": "object", "additionalProperties": false,' ...
    '   "required": ["pop_size", "generations", "tournament", "crossover_rate",' ...
    '     "mutation_factor", "repeats"],' ...
    '   "properties": {"pop_size": {"type": "integer", "minimum": 2},' ...
    '     "generations": {"type": "integer", "minimum": 0},' ...
    '     "tournament": {"type": "integer", "minimum": 1},' ...
    '     "crossover_rate": {"type": "number", "minimum": 0},' ...
    '     "mutation_factor": {"type": "number", "minimum": 0},' ...
    '     "repeats": {"type": "integer", "minimum": 1}}}}}']);
  s.details = jsondecode(['{"type": "object", "additionalProperties": false,' ...
    ' "required": ["evaluations", "generations"],' ...
    ' "properties": {"evaluations": {"type": "integer", "minimum": 0},' ...
    '   "generations": {"type": "integer", "minimum": 0}}}']);
end
