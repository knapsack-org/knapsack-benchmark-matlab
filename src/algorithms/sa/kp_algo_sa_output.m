function O = kp_algo_sa_output()
%KP_ALGO_SA_OUTPUT  Benchmark adapter and JSON description of 'sa'.
%   O.run(v, w, C, acfg, seed)  runs KP_ALGO_SA_MAIN, returns the common result struct
%   O.entry(acfg, env)          entry of the JSON "algorithms" array
%   O.schema.entry / .details   JSON Schema of that entry / of results.sa.details
  O = struct('run', @run_algo, 'entry', @build_entry, 'schema', describe());
end

function out = run_algo(v, w, C, acfg, seed)
  [items, info] = kp_algo_sa_main(v, w, C, acfg, seed);
  out = struct('label', label(), 'exact', false, 'proven_optimal', false, ...
               'items', items, 'working_memory_bytes', info.working_memory_bytes, ...
               'operations', info.proposals, 'operations_unit', 'move evaluations');
  out.details = struct('penalty', info.penalty, 'proposals', info.proposals, ...
                       'accepted', info.accepted, 't_start', info.t_start, 't_end', info.t_end);
end

function e = build_entry(acfg, env) %#ok<INUSD>
  L = kp_algo_sa_loader();
  e = struct('id', L.id, 'label', label(), 'description', L.description, 'short_label', L.short_label, 'exact', L.exact, ...
             'reference', L.reference, 'config', acfg);
end

function s = label()
  L = kp_algo_sa_loader();
  s = L.label;
end

function s = describe()
  s.entry = jsondecode(['{"type": "object", "additionalProperties": false,' ...
    ' "required": ["id", "label", "description", "short_label", "exact", "reference", "config"],' ...
    ' "properties": {"id": {"enum": ["sa"]}, "label": {"type": "string"}, "description": {"type": "string"},' ...
    ' "short_label": {"type": "string"}, "exact": {"type": "boolean"},' ...
    ' "reference": {"type": "boolean"},' ...
    ' "config": {"type": "object", "additionalProperties": false,' ...
    '   "required": ["penalty", "restarts", "steps_factor", "t0_factor", "t_end_factor", "repeats"],' ...
    '   "properties": {"penalty": {"type": ["string", "number"]},' ...
    '     "restarts": {"type": "integer", "minimum": 1},' ...
    '     "steps_factor": {"type": "number", "minimum": 0},' ...
    '     "t0_factor": {"type": "number", "minimum": 0},' ...
    '     "t_end_factor": {"type": "number", "minimum": 0},' ...
    '     "repeats": {"type": "integer", "minimum": 1}}}}}']);
  s.details = jsondecode(['{"type": "object", "additionalProperties": false,' ...
    ' "required": ["penalty", "proposals", "accepted", "t_start", "t_end"],' ...
    ' "properties": {"penalty": {"type": "number"},' ...
    '   "proposals": {"type": "integer", "minimum": 0}, "accepted": {"type": "integer", "minimum": 0},' ...
    '   "t_start": {"type": "number"}, "t_end": {"type": "number"}}}']);
end
