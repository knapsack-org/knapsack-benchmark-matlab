function out = kb_algo_bnb(v, w, C, acfg, seed) %#ok<INUSD>
%KB_ALGO_BNB  Benchmark adapter of 'bnb': run KB_KNAPSACK_BNB, return the common result struct.
%   OUT = KB_ALGO_BNB(V, W, C, ACFG, SEED): ACFG = cfg.bnb, SEED = cfg.seed + 1000 * k.
  [~, items, info] = kb_knapsack_bnb(v, w, C, acfg.max_nodes);
  out = struct('label', 'branch and bound (Dantzig bound, depth-first)', 'exact', true, ...
               'proven_optimal', info.proven_optimal, 'items', items, ...
               'working_memory_bytes', info.working_memory_bytes, ...
               'operations', info.nodes, 'operations_unit', 'nodes');
  out.details = struct('nodes', info.nodes, 'node_limit', acfg.max_nodes, ...
                       'node_limit_reached', ~info.proven_optimal);
end
